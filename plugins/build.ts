/**
 * Builds every plugin in this folder: Rust → core wasm (wasm32-unknown-unknown + wit-bindgen) →
 * component (`jco new`) → JS + core wasm in plugins/<name>/dist/plugin.js
 * (`jco transpile --instantiation async`), loadable by `@tscad/plugin-host` in Bun and browsers.
 *
 * A plugin with options (an `options-schema` in its `info()`, derived from its Rust options struct)
 * also gets them as WIT, `dist/<name>.wit` (see options-wit.ts), and `dist/index.ts`: the options as
 * a TypeScript interface and, for an operation, a typed function (`pluginOperation` from
 * `@tscad/modeling`). The TypeScript comes from `jco types` on that WIT, which keeps its doc comments.
 */
/* eslint-disable no-console -- a build script reporting what it built */

import { existsSync, mkdirSync, mkdtempSync, readdirSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { $ } from 'bun';
import { optionsWit } from './options-wit';

const root = path.join(import.meta.dir, '..');
const plugins = readdirSync(import.meta.dir, { withFileTypes: true })
  .filter(
    (entry) =>
      entry.isDirectory() && existsSync(path.join(import.meta.dir, entry.name, 'Cargo.toml')),
  )
  .map((entry) => entry.name);

await $`cargo build --release --target wasm32-unknown-unknown ${plugins.flatMap((p) => ['-p', `tscad-plugin-${p}`])}`
  .cwd(root)
  .env({ ...process.env, CARGO_PROFILE_RELEASE_STRIP: 'true' });
for (const plugin of plugins) {
  const core = path.join(
    root,
    'target/wasm32-unknown-unknown/release',
    `tscad_plugin_${plugin.replaceAll('-', '_')}.wasm`,
  );
  const outputDirectory = path.join(root, 'plugins', plugin, 'dist');
  mkdirSync(outputDirectory, { recursive: true }); // jco does not create it
  const component = path.join(outputDirectory, 'plugin.component.wasm');
  await $`bunx jco new ${core} -o ${component}`.quiet();
  await $`bunx jco transpile ${component} -o ${outputDirectory} --name plugin --instantiation async --no-nodejs-compat -q`;
  console.log(
    `${plugin}: ${(Bun.file(component).size / 1024).toFixed(0)} KiB component → ${outputDirectory}`,
  );
  await writeTypedExports(plugin, outputDirectory);
}

function kernelUnavailable(): never {
  throw new Error('the kernel is not available while building plugins');
}

/** Every import of a plugin, failing if called: `info()` needs no kernel. */
function unavailableImports(): object {
  return new Proxy({}, { get: () => new Proxy({}, { get: () => kernelUnavailable }) });
}

async function writeTypedExports(plugin: string, outputDirectory: string) {
  const { instantiate } = await import(path.join(outputDirectory, 'plugin.js'));
  const exports = await instantiate(
    async (file: string) =>
      WebAssembly.compile(await Bun.file(path.join(outputDirectory, file)).arrayBuffer()),
    unavailableImports(),
  );
  const { optionsSchema } = exports.info() as { optionsSchema: string };
  if (!optionsSchema) return;
  const wit = path.join(outputDirectory, `${plugin}.wit`);
  await Bun.write(wit, optionsWit(plugin, JSON.parse(optionsSchema)));

  const types = mkdtempSync(path.join(tmpdir(), `tscad-plugin-${plugin}-`));
  try {
    await $`bunx jco types ${wit} --world-name ${plugin} -o ${types} -q`.quiet();
    const optionsFile = path.join(types, 'interfaces', `tscad-${plugin}-options.d.ts`);
    const declarations = await Bun.file(optionsFile).text();
    const options = declarations
      .replace(/^\/\*\* @module .*\*\*\/\n/, '')
      // jco types `list<f64>` and the like as typed arrays, but options travel as JSON arrays.
      .replaceAll(
        /\b(?:Float32|Float64|Int8|Int16|Int32|Uint8|Uint16|Uint32)Array\b/g,
        'Array<number>',
      );
    if (options.includes('import(')) {
      throw new Error(`${optionsFile}: options may only use their own types (for now)`);
    }

    const name = plugin.replaceAll(/-(\w)/g, (_, letter: string) => letter.toUpperCase());
    const type = `${name[0]!.toUpperCase()}${name.slice(1)}Options`;
    const documentation = new RegExp(
      String.raw`(/\*\*(?:(?!\*/)[\s\S])*\*/)\nexport interface ${type} \{`,
    ).exec(options)?.[1];
    if (!documentation) throw new Error(`${optionsFile}: no documented interface ${type}`);
    const isOperation = typeof exports.evaluate === 'function';
    const { name: packageName } = (await Bun.file(
      path.join(import.meta.dir, plugin, 'package.json'),
    ).json()) as { name: string };

    const lines = [
      `// Generated by plugins/build.ts from ${plugin}.wit. Do not edit.`,
      ...(isOperation
        ? [`import { pluginOperation, type Shape } from '@tscad/modeling';`, '']
        : ['']),
      options.trim(),
      ...(isOperation
        ? [
            '',
            `const operation = pluginOperation<${type}>('${plugin}');`,
            '',
            functionDocumentation(documentation, packageName),
            `export function ${name}(options: ${type}, ...children: Shape[]): Shape {`,
            '  return operation(options, ...children);',
            '}',
          ]
        : []),
      '',
    ];
    // jco leaves a trailing space on blank doc comment lines.
    await Bun.write(
      path.join(outputDirectory, 'index.ts'),
      lines.join('\n').replaceAll(/[ \t]+$/gm, ''),
    );
    console.log(`${plugin}: typed exports → ${path.join(outputDirectory, 'index.ts')}`);
  } finally {
    rmSync(types, { recursive: true, force: true });
  }
}

/**
 * The options' documentation for the operation's function: where to import it from, and the
 * category the API reference lists it under.
 */
function functionDocumentation(documentation: string, packageName: string): string {
  const lines = documentation.split('\n');
  const firstTag = lines.findIndex((line) => line.startsWith(' * @'));
  const textEnd = firstTag === -1 ? lines.length - 1 : firstTag;
  lines.splice(textEnd, 0, ` * Import it from \`${packageName}\`.`, ' * ');
  lines.splice(-1, 0, ' * @category Plugins');
  return lines.join('\n');
}
