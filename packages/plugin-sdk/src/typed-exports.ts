/**
 * A plugin package's typed exports, from the TypeScript that `jco types` makes of its options WIT:
 * `index.d.ts` with the options as interfaces and `index.js`, which for an operation plugin exports
 * a typed function (`grid(options, ...children)`, built with `pluginOperation` from
 * `@tscad/modeling`).
 */

/** `export-3mf` → `export3mf`, the name of the operation's function. */
export function functionName(plugin: string): string {
  return plugin.replaceAll(/-(\w)/g, (_, letter: string) => letter.toUpperCase());
}

/** `grid` → `GridOptions`, the name jco gives the `<plugin>-options` record. */
export function optionsType(plugin: string): string {
  const name = functionName(plugin);
  return `${name[0]!.toUpperCase()}${name.slice(1)}Options`;
}

/**
 * The options' documentation for the operation's function: where to import it from, and the
 * category the API reference lists it under.
 */
function functionDocumentation(documentation: string, packageName: string): string {
  const lines = documentation.split('\n');
  const firstTag = lines.findIndex((line) => line.startsWith(' * @'));
  const textEnd = firstTag === -1 ? lines.length - 1 : firstTag;
  lines.splice(textEnd, 0, ` * Import it from \`${packageName}\`.`, ' *');
  lines.splice(-1, 0, ' * @category Plugins');
  return lines.join('\n');
}

export type TypedExportsInput = {
  /** The plugin's name, as its `info()` reports it. */
  plugin: string;
  /** The npm package the exports are imported from. */
  packageName: string;
  /** Whether the plugin is an operation (and so gets a function). */
  isOperation: boolean;
  /** jco's declarations of the plugin's options interface (`interfaces/tscad-<plugin>-options.d.ts`). */
  declarations: string;
};

export function typedExports({
  plugin,
  packageName,
  isOperation,
  declarations,
}: TypedExportsInput): { js: string; dts: string } {
  const options = declarations
    .replace(/^\/\*\* @module .*\*\*\/\n/, '')
    // jco types `list<f64>` and the like as typed arrays, but options travel as JSON arrays.
    .replaceAll(
      /\b(?:Float32|Float64|Int8|Int16|Int32|Uint8|Uint16|Uint32)Array\b/g,
      'Array<number>',
    )
    // jco leaves a trailing space on blank doc comment lines.
    .replaceAll(/[ \t]+$/gm, '')
    .trim();
  if (options.includes('import(')) {
    throw new Error(`${plugin}: options may only use their own types (for now)`);
  }
  const name = functionName(plugin);
  const type = optionsType(plugin);
  const documentation = new RegExp(
    String.raw`(/\*\*(?:(?!\*/)[\s\S])*\*/)\nexport interface ${type} \{`,
  ).exec(options)?.[1];
  if (!documentation) throw new Error(`${plugin}: no documented interface ${type}`);

  const header = `// Generated by tscad-plugin build from ${plugin}.wit. Do not edit.`;
  if (!isOperation) return { js: `${header}\nexport {};\n`, dts: `${header}\n\n${options}\n` };
  return {
    js: [
      header,
      `import { pluginOperation } from '@tscad/modeling';`,
      '',
      `const operation = pluginOperation('${plugin}');`,
      '',
      `export function ${name}(options, ...children) {`,
      '  return operation(options, ...children);',
      '}',
      '',
    ].join('\n'),
    dts: [
      header,
      `import type { Shape } from '@tscad/modeling';`,
      '',
      options,
      '',
      functionDocumentation(documentation, packageName),
      `export declare function ${name}(options: ${type}, ...children: Shape[]): Shape;`,
      '',
    ].join('\n'),
  };
}
